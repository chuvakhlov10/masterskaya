import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const LOCAL_REQUIRE = /require\((['"])(\.\/[^'"]+)\1\)/g;

const TARGETS = [
  {
    name: 'storage',
    service: 'masterskaya-storage-gateway',
    entry: 'yandex-storage-function/device-index.js',
  },
  {
    name: 'ably',
    service: 'masterskaya-ably-auth',
    entry: 'yandex-function/device-aware-index.js',
  },
];

function posix(value) {
  return value.split(path.sep).join('/');
}

function moduleId(absolutePath, rootDir) {
  return posix(path.relative(rootDir, absolutePath));
}

function resolveLocalModule(fromFile, request) {
  const resolved = path.resolve(path.dirname(fromFile), request);
  const candidates = [resolved, `${resolved}.js`, path.join(resolved, 'index.js')];
  const found = candidates.find(candidate => fs.existsSync(candidate) && fs.statSync(candidate).isFile());
  if (!found) throw new Error(`LOCAL_MODULE_NOT_FOUND: ${request} from ${fromFile}`);
  return found;
}

export function bundleCommonJs({ entryPath, rootDir = REPO_ROOT, buildId, buildDate }) {
  const entryAbsolute = path.resolve(rootDir, entryPath);
  const modules = new Map();

  function collect(filePath) {
    const absolutePath = path.resolve(filePath);
    const id = moduleId(absolutePath, rootDir);
    if (modules.has(id)) return id;

    const original = fs.readFileSync(absolutePath, 'utf8');
    modules.set(id, null);
    const transformed = original.replace(LOCAL_REQUIRE, (_match, _quote, request) => {
      const dependency = resolveLocalModule(absolutePath, request);
      const dependencyId = collect(dependency);
      return `__bundleRequire(${JSON.stringify(dependencyId)})`;
    });
    modules.set(id, transformed);
    return id;
  }

  const entryId = collect(entryAbsolute);
  const moduleBlocks = [...modules.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([id, source]) => `${JSON.stringify(id)}: function(module, exports, __bundleRequire, require) {\n${source}\n}`)
    .join(',\n');

  const output = `'use strict';\n\n// Generated by scripts/build-yandex-functions.mjs. Do not edit this bundle manually.\nconst __nativeRequire = require;\nconst __modules = {\n${moduleBlocks}\n};\nconst __cache = Object.create(null);\nfunction __bundleRequire(id) {\n  if (__cache[id]) return __cache[id].exports;\n  const factory = __modules[id];\n  if (!factory) throw new Error('BUNDLED_MODULE_NOT_FOUND: ' + id);\n  const module = { exports: {} };\n  __cache[id] = module;\n  factory(module, module.exports, __bundleRequire, __nativeRequire);\n  return module.exports;\n}\nmodule.exports = __bundleRequire(${JSON.stringify(entryId)});\n`;

  return output
    .replaceAll('__MASTERSKAYA_BUILD_ID__', String(buildId))
    .replaceAll('__MASTERSKAYA_BUILD_DATE__', String(buildDate));
}

function sha256(content) {
  return crypto.createHash('sha256').update(content).digest('hex');
}

export function buildAll({
  rootDir = REPO_ROOT,
  outputDir = path.join(rootDir, 'dist', 'yandex'),
  buildId = process.env.MASTERSKAYA_BUILD_ID || process.env.GITHUB_SHA || 'local',
  buildDate = process.env.MASTERSKAYA_BUILD_DATE || new Date().toISOString(),
} = {}) {
  fs.rmSync(outputDir, { recursive: true, force: true });
  fs.mkdirSync(outputDir, { recursive: true });

  const manifest = {
    schemaVersion: 1,
    buildId: String(buildId),
    buildDate: String(buildDate),
    targets: {},
  };

  for (const target of TARGETS) {
    const content = bundleCommonJs({
      entryPath: target.entry,
      rootDir,
      buildId,
      buildDate,
    });
    const targetDir = path.join(outputDir, target.name);
    fs.mkdirSync(targetDir, { recursive: true });
    const outputPath = path.join(targetDir, 'index.js');
    fs.writeFileSync(outputPath, content, 'utf8');
    manifest.targets[target.name] = {
      service: target.service,
      entry: target.entry,
      output: posix(path.relative(rootDir, outputPath)),
      bytes: Buffer.byteLength(content),
      sha256: sha256(content),
    };
  }

  fs.writeFileSync(path.join(outputDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  return manifest;
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  const manifest = buildAll();
  for (const [name, target] of Object.entries(manifest.targets)) {
    console.log(`${name}: ${target.output} (${target.bytes} bytes, sha256 ${target.sha256})`);
  }
}
